package com.htmlbuilder.generator.agent.graph.node;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.htmlbuilder.generator.agent.AnthropicChatLanguageModel;
import com.htmlbuilder.generator.agent.graph.CodeIOUtil;
import com.htmlbuilder.generator.agent.graph.GenerationState;
import com.htmlbuilder.generator.agent.graph.ProgressRegistry;
import com.htmlbuilder.generator.agent.graph.PromptConstants;
import com.htmlbuilder.generator.agent.tool.PackageTool;
import org.bsc.langgraph4j.action.NodeAction;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.nio.file.Path;
import java.util.Map;
import java.util.function.Consumer;

/**
 * 项目配置节点：生成 package.json / .gitignore / README.md。
 * - 读取 server.js 内容，动态扫描 require() 依赖生成 package.json。
 * - 若 state 中存在 NPM_ERROR（重试模式），调用 AI 修复 package.json 中的依赖版本错误。
 */
@Component
public class ProjectConfigNode implements NodeAction<GenerationState> {

    private static final ObjectMapper objectMapper = new ObjectMapper();

    private final AnthropicChatLanguageModel chatModel;
    private final PackageTool packageTool;
    private final ProgressRegistry progressRegistry;

    public ProjectConfigNode(AnthropicChatLanguageModel chatModel, PackageTool packageTool, ProgressRegistry progressRegistry) {
        this.chatModel = chatModel;
        this.packageTool = packageTool;
        this.progressRegistry = progressRegistry;
    }

    @Override
    public Map<String, Object> apply(GenerationState state) {
        Long taskId = state.taskId();
        Consumer<String> callback = progressRegistry.get(taskId);
        if (callback == null) {
            callback = s -> {};
        }

        String projectDir = state.projectDir();
        callback.accept("[打包] 正在生成项目配置文件...");

        try {
            generateProjectConfig(projectDir);
        } catch (IOException e) {
            throw new RuntimeException("[打包] 项目配置生成失败: " + e.getMessage(), e);
        }

        // 重试模式：npm install 失败后用 AI 修复 package.json
        String npmError = state.npmError();
        if (npmError != null && !npmError.isBlank()) {
            callback.accept("[打包] 检测到 npm 错误，AI 正在修复 package.json...");
            fixPackageJsonWithAI(projectDir, npmError, callback);
        }

        callback.accept("[打包] 项目配置文件生成完成");
        return Map.of();
    }

    private void generateProjectConfig(String projectDir) throws IOException {
        // 读取 server.js 内容，动态扫描 require() 依赖
        String serverJsContent = CodeIOUtil.readFile(projectDir, "server.js");
        String packageJson = packageTool.generatePackageJson(
                "generated-website",
                "AI generated website project",
                serverJsContent
        );
        CodeIOUtil.writeCodeFile(projectDir, "package.json", packageJson);
        CodeIOUtil.writeCodeFile(projectDir, ".gitignore", packageTool.generateGitignore());
        CodeIOUtil.writeCodeFile(projectDir, "README.md", generateReadme());
    }

    /**
     * 将 npm install 错误输出交给大模型分析，修复 package.json 中的依赖版本错误
     */
    private void fixPackageJsonWithAI(String projectDir, String npmErrorOutput, Consumer<String> callback) {
        Path packageJsonPath = Path.of(projectDir, "package.json");
        String currentPackageJson = "";
        try {
            String read = CodeIOUtil.readFile(projectDir, "package.json");
            if (read != null) {
                currentPackageJson = read;
            }
        } catch (IOException e) {
            callback.accept("[依赖] 读取 package.json 失败: " + e.getMessage());
            return;
        }

        String fullPrompt = PromptConstants.FIX_PACKAGE_JSON
                + "\n\n当前 package.json:\n" + currentPackageJson
                + "\n\nnpm install 错误日志:\n" + npmErrorOutput
                + "\n\n请输出修复后的 package.json：";

        String fixedJson = chatModel.streamChat(fullPrompt, callback);
        fixedJson = CodeIOUtil.extractJson(CodeIOUtil.stripCodeFences(fixedJson));

        try {
            // 验证是合法 JSON
            objectMapper.readTree(fixedJson);
            CodeIOUtil.writeCodeFile(projectDir, "package.json", fixedJson);
            callback.accept("[依赖] AI 已修复 package.json");
        } catch (Exception e) {
            callback.accept("[依赖] AI 修复的 package.json 无效: " + e.getMessage());
        }
    }

    private static String generateReadme() {
        return """
# Generated Website

This project was automatically generated by AI.

## Quick Start

```bash
npm install
npm start
```

Then open http://localhost:3000 in your browser.

## Project Structure

```
├── public/          # Static files (HTML, CSS, JS)
│   ├── css/
│   ├── js/
│   └── images/
├── database/        # SQLite schema
├── server.js        # Express server
└── package.json     # Dependencies
```
""";
    }
}
